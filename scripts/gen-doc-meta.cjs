/**
 * Doc metadata generator.
 *
 * Walks pages/**\/*.{md,mdx}, parses each doc's frontmatter, and does two things:
 *
 *   1. Writes src/data/doc-dates.ts — a map from URL pathname to
 *      { datePublished, dateModified } that SiteMeta imports so the
 *      TechArticle JSON-LD reflects per-page frontmatter instead of a
 *      site-level floor.
 *
 *   2. Maintains a visible "Updated {Month YYYY}" stamp inside every doc.
 *      The stamp lives between <!-- akg:updated --> markers, is re-derived
 *      from dateModified on every build, and is idempotent (re-running the
 *      script without bumping any date is a no-op).
 *
 * Run automatically by `pnpm dev` and `pnpm build` (alongside gen:css /
 * gen:og). Safe to run ad-hoc as `pnpm gen:dates`.
 */
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const PAGES_DIR = path.join(ROOT, "pages");
const OUT_TS = path.join(ROOT, "src", "data", "doc-dates.ts");

// MDX does not have a universal HTML-comment syntax that stays parseable
// across .md and .mdx, so the injected block is a plain <span> and we
// identify it by its class attribute for idempotent updates.
// Root doc is mounted at "/" (see zudoku.config.tsx navigation override),
// not at /docs/introduction/what-are-api-keys. The stamp goes inside the
// hero block manually, so skip stamp injection here — but still include
// the entry in doc-dates.ts under "/".
const ROOT_DOC_REL = "docs/introduction/what-are-api-keys";

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, files);
    else if (entry.isFile() && /\.(md|mdx)$/.test(entry.name)) files.push(full);
  }
  return files;
}

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return { data: {}, body: raw, frontmatterEnd: 0 };
  const block = match[1];
  const data = {};
  for (const line of block.split(/\r?\n/)) {
    const m = line.match(/^([A-Za-z_][\w-]*)\s*:\s*(.*)$/);
    if (!m) continue;
    let value = m[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    data[m[1]] = value;
  }
  return { data, body: raw.slice(match[0].length), frontmatterEnd: match[0].length };
}

const MONTHS = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
];

function formatMonthYear(iso) {
  // Parse as UTC to avoid TZ drift on "2026-04-22" strings.
  const [y, m] = iso.split("-").map(Number);
  if (!y || !m) return iso;
  return `${MONTHS[m - 1]} ${y}`;
}

function relToHref(relPath) {
  // "docs/introduction/how-api-keys-work.md" -> "/docs/introduction/how-api-keys-work"
  const noExt = relPath.replace(/\.(md|mdx)$/, "");
  if (noExt === ROOT_DOC_REL) return "/";
  return "/" + noExt;
}

function buildStampBlock(dateModified) {
  const label = formatMonthYear(dateModified);
  // A plain inline span keeps the markup usable in both .md and .mdx
  // without introducing a React component dependency into every doc.
  return `<span class="akg-updated" data-updated="${dateModified}">Updated ${label}</span>\n`;
}

function upsertStamp(body, dateModified) {
  const block = buildStampBlock(dateModified);
  const existing = /<span class="akg-updated" data-updated="[^"]*">Updated [^<]*<\/span>\r?\n?/;
  if (existing.test(body)) {
    return body.replace(existing, block);
  }
  // Insert as the first content after any leading blank lines.
  const leading = body.match(/^\s*/)[0];
  return leading + block + "\n" + body.slice(leading.length);
}

const files = walk(PAGES_DIR);
const dates = {};
let stampWrites = 0;

for (const abs of files) {
  const rel = path.relative(PAGES_DIR, abs).split(path.sep).join("/");
  const raw = fs.readFileSync(abs, "utf-8");
  const { data, body, frontmatterEnd } = parseFrontmatter(raw);

  if (!data.datePublished || !data.dateModified) {
    console.warn(`gen-doc-meta: ${rel} missing datePublished/dateModified — skipping`);
    continue;
  }

  const href = relToHref(rel);
  dates[href] = {
    datePublished: data.datePublished,
    dateModified: data.dateModified,
  };

  // Skip stamp injection for the root hero doc — it owns its own visible
  // "Updated" marker inside the hero block.
  if (rel.replace(/\.(md|mdx)$/, "") === ROOT_DOC_REL) continue;

  const nextBody = upsertStamp(body, data.dateModified);
  if (nextBody !== body) {
    const head = raw.slice(0, frontmatterEnd);
    fs.writeFileSync(abs, head + nextBody);
    stampWrites += 1;
  }
}

const header = [
  "// AUTO-GENERATED by scripts/gen-doc-meta.cjs.",
  "// Do not edit by hand — update frontmatter datePublished/dateModified",
  "// in the relevant doc under pages/ and re-run `pnpm gen:dates`.",
  "",
  "export interface DocDates {",
  "  datePublished: string;",
  "  dateModified: string;",
  "}",
  "",
  "export const DOC_DATES: Record<string, DocDates> = ",
].join("\n");

const sortedEntries = Object.fromEntries(
  Object.entries(dates).sort(([a], [b]) => a.localeCompare(b)),
);

fs.writeFileSync(OUT_TS, header + JSON.stringify(sortedEntries, null, 2) + ";\n");
console.log(
  `gen-doc-meta: wrote ${Object.keys(dates).length} date entries, updated ${stampWrites} stamp blocks`,
);
